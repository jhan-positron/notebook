#!/usr/bin/env python3
"""Write compare-humanized-n-not.md: every difference between tron-intuition-claude.html and
tron-intuition-claude-humanized.html, in full (before and after), and nothing that is the same."""
import re, html, difflib

D = "/home/jhan/workspace/intel-AMX/PR3879/new-PRs/new-counters/"
A = D + "tron-intuition-claude.html"
B = D + "tron-intuition-claude-humanized.html"
OUT = D + "compare-humanized-n-not.md"

BLOCK = re.compile(r'(?s)<(h1|h2|h3|p|li|dt|dd|caption|figcaption|div class="short"|div class="rule-t"|div class="rule-b"|div class="sub")[^>]*>(.*?)</(?:h1|h2|h3|p|li|dt|dd|caption|figcaption|div)>')

def blocks(path):
    t = open(path).read()
    t = re.sub(r'(?s)<svg .*?</svg>', '', t)
    t = re.sub(r'(?s)<pre>.*?</pre>', '', t)
    t = re.sub(r'(?s)<nav class="toc">.*?</nav>', '', t)
    # the Short version box holds a list: split it into its lead paragraph and the list items
    t = re.sub(r'(?s)<div class="short">(.*?)\n<ul>(.*?)</ul></div>', r'<p class="short">\1</p>\n<ul>\2</ul>', t)
    out = []; section = "header"
    for m in BLOCK.finditer(t):
        tag, inner = m.group(1), m.group(2)
        if tag in ("h2", "h3"):
            section = plain(inner)
        out.append((section, tag, inner.strip()))
    return out

def plain(s):
    s = re.sub(r'<[^>]+>', '', s)
    return re.sub(r'\s+', ' ', html.unescape(s)).strip()

def svg_texts(path):
    t = open(path).read()
    res = []
    for k, sv in enumerate(re.findall(r'(?s)<svg .*?</svg>', t), 1):
        for m in re.finditer(r'<text [^>]*>(.*?)</text>', sv):
            res.append(("Figure %d" % k, html.unescape(m.group(1))))
    return res

def md_quote(s):
    return "> " + s.replace("\n", "\n> ")

def main():
    a, b = blocks(A), blocks(B)
    sm = difflib.SequenceMatcher(a=[x[2] for x in a], b=[y[2] for y in b], autojunk=False)
    items = []
    for op, i1, i2, j1, j2 in sm.get_opcodes():
        if op == "equal":
            continue
        olds, news = a[i1:i2], b[j1:j2]
        n = max(len(olds), len(news))
        for k in range(n):
            o = olds[k] if k < len(olds) else None
            w = news[k] if k < len(news) else None
            items.append((o, w))
    # figure text
    fa, fb = svg_texts(A), svg_texts(B)
    fsm = difflib.SequenceMatcher(a=[x[1] for x in fa], b=[y[1] for y in fb], autojunk=False)
    fitems = []
    for op, i1, i2, j1, j2 in fsm.get_opcodes():
        if op == "equal":
            continue
        fitems.append((fa[i1:i2], fb[j1:j2]))

    markup_only = sum(1 for o, w in items if o and w and plain(o[2]) == plain(w[2]))
    text_changes = len(items) - markup_only
    L = []
    L.append("# Differences between tron-intuition-claude.html and tron-intuition-claude-humanized.html\n")
    L.append("Short version. The two pages differ in %d prose blocks and %d figure text runs. %d of the prose blocks differ in wording, and %d differ only in markup (bold tags removed, text unchanged). Every number, table, figure geometry and code block is identical.\n" % (len(items), len(fitems), text_changes, markup_only))
    L.append("Words used here: a block is one paragraph, list item, heading, caption or glossary entry of the page. Before = tron-intuition-claude.html. After = tron-intuition-claude-humanized.html. Generated by exec/tron-intuition-20261007/compare_pages.py from the two files on disk, so only what differs is listed.\n")
    L.append("## Prose blocks\n")
    for n, (o, w) in enumerate(items, 1):
        sec = (o or w)[0]
        tag = (o or w)[1]
        L.append("### %d. %s (%s)\n" % (n, sec, tag))
        if o and w and plain(o[2]) == plain(w[2]):
            L.append("Markup only: bold tags removed, text unchanged.\n")
            L.append("Before (HTML):\n")
            L.append(md_quote("`" + o[2].replace("`", "'") + "`") + "\n")
            L.append("After (HTML):\n")
            L.append(md_quote("`" + w[2].replace("`", "'") + "`") + "\n")
            continue
        if o:
            L.append("Before:\n")
            L.append(md_quote(plain(o[2])) + "\n")
        else:
            L.append("Before: (no such block)\n")
        if w:
            L.append("After:\n")
            L.append(md_quote(plain(w[2])) + "\n")
        else:
            L.append("After: (block removed)\n")
        if o and w and ("<b>" in o[2] and "<b>" not in w[2]):
            L.append("Also: the bold label at the start of the block was removed.\n")
    L.append("## Figure text\n")
    L.append("Figure text is drawn as SVG text lines, wrapped at about 170 characters. A changed sentence therefore appears as a run of changed lines.\n")
    for n, (olds, news) in enumerate(fitems, 1):
        fig = (olds or news)[0][0]
        L.append("### F%d. %s\n" % (n, fig))
        L.append("Before:\n")
        L.append(md_quote("\n".join(x[1] for x in olds) if olds else "(no such line)") + "\n")
        L.append("After:\n")
        L.append(md_quote("\n".join(x[1] for x in news) if news else "(line removed)") + "\n")
    open(OUT, "w").write("\n".join(L))
    print("wrote", OUT, "prose diffs", len(items), "figure diffs", len(fitems))

if __name__ == "__main__":
    main()
